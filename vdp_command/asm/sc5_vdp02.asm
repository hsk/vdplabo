; SCREEN 5 HMMM サンプル

CHGMOD  equ     $005F           ; 画面モード変更 (A=モード)
VDP_P0  equ     $98             ; VRAMデータポート
VDP_P1  equ     $99             ; レジスタ書き込みポート
VDP_P3  equ     $9B             ; 連続書き込みポート

        org     $4000           ; ROMの開始アドレス
        db      "AB"            ; ROMマジックID
        dw      init            ; パワーオン・リセット時の開始アドレス
        ds      12, 0           ; 予約領域

init:
        ; SCREEN 5 に切り替え
        ld      a, 5            ; SCREEN 5
        call    CHGMOD

        di                      ; VDPを直接制御するため割り込み禁止
        ; HMMC でVRAMにデータ転送 -----------------
        ; 2. 表画面の左上（VRAMアドレス #00000）を書き込みモードで開く
        ld      a, $00
        out     (VDP_P1), a
        ld      a, $40          ; 書き込み指示ビット込みのアドレス上位
        out     (VDP_P1), a
        ; 3. 画像データ（8バイト）をVRAMの一行目にストレート転送
        ld      hl, image_data   
        ld      bc, 8
vram_loop:
        ld      a, (hl)
        out     (VDP_P0), a
        inc     hl
        dec     bc
        ld      a, b
        or      c
        jr      nz, vram_loop
        ; HMMC でVRAMにデータ転送 終了 -----------------
        ; 4. HMMMコマンドを使って、一列のデータを (16, 16) へ 16x16 で転送
        call    wait_vdp        ; VDPの準備完了を待つ
        ld      hl, param_hmmm  ; HMMMのパラメータテーブル
        call    set_vdp_regs    ; VDPレジスタに転送
        ei                      ; 割り込み許可
main:
        jr      main
;--------------------------------------------------------
; サブルーチン: VDPコマンドレジスタ(R#32〜R#46)の一括設定
;--------------------------------------------------------
set_vdp_regs:
        ld      a, 32            ; レジスタ間接指定の開始番号 (R#32)
        out     (VDP_P1), a
        ld      a, 17 + $80      ; R#17に32を指定
        out     (VDP_P1), a
        ; ポート#1に対して、R#32〜R#46までの15バイトを連続出力
        ld      c, VDP_P3
        ld      b, 15
        otir
        ret
;--------------------------------------------------------
; サブルーチン: VDPコマンドの実行完了待ち
;--------------------------------------------------------
wait_vdp:
        ld      a, 2            ; ステータスレジスタ S#2 を指定
        out     (VDP_P1), a
        ld      a, 15 + $80
        out     (VDP_P1), A
.wait_loop:
        in      A, (VDP_P1)     ; S#2 を読み出し
        and     $01             ; CEフラグ（ビット0）をチェック
        jr      nz, .wait_loop  ; CE=1（実行中）ならループ
        ; ステータスレジスタを S#0 に戻しておく（BIOS互換のため）
        xor     a
        out     (VDP_P1), a
        ld      a, 15 + $80
        out     (VDP_P1), a
        ret
;--------------------------------------------------------
; HMMM パラメータデータ（各項目2バイト、下位・上位バイトの順）
;--------------------------------------------------------
param_hmmm:
        dw      0               ; R#32-33: SX (ソースX = 0)
        dw      0               ; R#34-35: SY (ソースY = 0)
        dw      16              ; R#36-37: DX (デスティネーションX = 16)
        dw      16              ; R#38-39: DY (デスティネーションY = 16)
        dw      16              ; R#40-41: NX (幅 = 16ドット)
        dw      1               ; R#42-43: NY (高さ = 1ドット)
        dw      0               ; R#44-45: 引数CLR/ARG (カラーコードの下位上位・方向フラグ)
        db      $D0             ; R#46:    CMD (コマンド種別 = HMMM)
;--------------------------------------------------------
; 画像データ
;--------------------------------------------------------
image_data:
        db      $00,$0F,$FF,$FF,$FF,$FF,$F0,$00
end:
        ds      $8000 - $, $FF
