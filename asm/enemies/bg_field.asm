    ld (bg_stripe_color_table2+16),a
    ret
bg_field_pattern_table_init:
    ; SCREEN2 のパターンテーブル先頭へアミアミを配置
    ld hl, 00000h+8*8
    ld b, 3
    send_pattern_table_loop:
        push bc
        ld b, 64/2
        send_pattern_table:
            ;      12345678
            ld a, 010101010b
            call WRTVRM
            inc hl
            ;      12345678
            ld a, 001010101b
            call WRTVRM
            inc hl
            djnz send_pattern_table
        ; ３つに分かれてる次のパターンテーブルの先頭に移動
        ld bc, 256*8 - 64
        add hl, bc
        pop bc
        djnz send_pattern_table_loop
    ret
