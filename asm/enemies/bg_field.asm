bg_pre_draw:
    ; bg_stripe_color_table1 は同じ16色周期を2周分並べているため、
    ; player_z を加算した位置から16バイト連続コピーするだけで
    ; (i + player_z) & 15 と同じ結果になる。
    ; 描画ループ内で AND や加算を行わないため高速。
    ; player_z に応じた色テーブルを生成
    ; bg_stripe_color_table2[i] = bg_stripe_color_table[(i + player_z) & (ZSTEP-1)]
    ld a,(player_z)
    inc a
    ld (player_z),a
    and ZSTEP-1
    ld e,a
    ld d,0
    ld hl,bg_stripe_color_table1
    add hl,de
    ld de, bg_stripe_color_table2
    REPT 16
    ldi
    ENDM

    ret
bg_draw:
    ; スプライトテーブルのアドレスを取得してhlに入れる
    ld a,(player_y)
    sub 6
    add a,a
    ld de, bg_stripe_tables
    ld h,0
    ld l,a
    add hl, de
    ld e,(hl)
    inc hl
    ld d,(hl)
    ex de, hl

    ; SCREEN2 カラーテーブル ($2000-$37FF) 設定
    ; stripe_table の値(0-4)を bg_stripe_color_table2 で色コードへ変換
    ; 各ラインの色を8バイト分書き込む
    ld e,020h + 040h ; 02000h の上位バイトに転送用の040hを加えるc下位バイトは0
    ld b, 3 ; スクリーン2,4は3つに分かれてるので３回ループ
    ld d, 8*8 ; 転送アドレスのズレ８キャラ分
    ld c, 099h ; アドレス増分
    exx
    ld h,bg_stripe_color_table2/256
    ld c,098h
    exx
    di
    ld (bg_stack_pos),sp ; 20 スタックを用いた転送をするためにスタックポインタ保存
    ld sp,hl ; 6 ストライプカラーテーブル位置をスタックポインタに設定
    color_table_loop:
        ; VDP VRAM書き込みアドレスを $2000+8*8+800h*n に設定
        out (c),d
        out (c),e
        exx
        REPT 32
            ; 2
            pop de ; 7 pop して２バイト読み込みかつポインタを進める
            ; stripe_table の値は色コードそのものではなく 0～16 のインデックス。
            ; bg_stripe_color_table2 の先頭アドレスを加算して
            ; 色コードテーブルを参照する。
            ld a,e ; 4T
            add a,bg_stripe_color_table2&255; 7T ; レジスタにしたいけど空きがない
            ; dec b; add a,b; は 4T 4Tで8T
            ld l,a
            outi ; out (c),(hl); 16T out (c),(hl); inc hl; dec b をまとめて実行
                               ; ld a,(hl); 7T; out (098h),a ; 11T で18T
                               ; out (c),aは ; 12T
            ; 3
            ld a,d ; 4 15T 15*32+82T = 562
            ; D側のインデックスも同様に色コードへ変換。
            add a,bg_stripe_color_table2&255
            ld l,a
            outi
        ENDM
        exx
        ld a, e ; 4 転送先アドレスを 0800h 進める
        add a, 8; 7
        ld e, a ; 4
        dec b
        jp nz, color_table_loop
    ; スタックポインタを復帰する
    ld sp,(bg_stack_pos) ; 20
    ei
    ret
