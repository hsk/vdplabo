bg_stripe_color_table1_init:
    ; 転送先アドレス
    ld hl,bg_stripe_color_table1
    ld c,2
    tr2:
        ; 転送元アドレス
        ld de,bg_stripe_color_table
        ld b,4
        tr:
            ld a,(de)
            inc de
            ld (hl),a
            inc hl
            ld (hl),a
            inc hl
            ld (hl),a
            inc hl
            ld (hl),a
            inc hl
            djnz tr
        dec c
        jr nz,tr2
    ; bg_stripe_color_table2 は 0～15 の16エントリを毎フレーム書き換える。
    ; 16番目の値は背景色(インデックス16用)として固定。
