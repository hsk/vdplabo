class LogoChar:
    def __init__(self, matrix, index):
        X_OFFSETS = [0, 30, 60, 100, 140, 180]  # 各文字の本来の相対間隔
        self.index = index
        self.offset_x = X_OFFSETS[index]  # 2倍拡大分
        self.x = 0
        self.y = 0
        self.image = self._create_image(matrix)

    def _create_image(self, matrix):
        surf = pygame.Surface((32, 32))
        surf.fill(BLACK)
        surf.set_colorkey(BLACK)
        for y in range(16):
            for x in range(16):
                if matrix[y][x] == 1:
                    pygame.draw.rect(surf, WHITE, (x * 2, y * 2, 2, 2))
        return surf

    def draw(self, surface):
        surface.blit(self.image, (self.x, self.y))

class LogoAnimator:
    def __init__(self):
        # 文字オブジェクトの生成（リスト内包表記できれいに作成）
        self.chars = [LogoChar(matrix, i) for i, matrix in enumerate(LOGO_DATA)]
        # 演出関数を配列にまとめる（★ここがポイント！）
        self.phases = [self.anim_slide_in, self.anim_expand, self.anim_drop, self.anim_stay]
        self.phase = 0
        self.cnt = 0

    def update(self):
        # 現在のフェーズの関数を取り出して実行
        anim_func = self.phases[self.phase]
        is_finished = anim_func(self.chars, self.cnt)
        self.cnt += 1
        # アニメーションが終了条件を満たしたら次のフェーズへ
        if is_finished:
            self.cnt = 0
            self.phase = (self.phase + 1) % len(self.phases)

    # --- [演出管理] 各フェーズのアニメーション関数 ---
    # 引数に一括で (全文字リスト, 経過フレームcnt) を受け取るように統一
    def anim_slide_in(self, chars, cnt):
        """Phase 1: 全文字が重なったまま右から左へスライド"""
        x = 256 - cnt * 4
        for c in chars:
            c.x = x
            c.y = 60
        return x <= 24  # 条件達成でTrue（次のフェーズへ）

    def anim_expand(self, chars, cnt):
        """Phase 2: 定位置でアコーディオンのように横に展開"""
        t = 1 - (32 - cnt) / 32
        for c in chars:
            c.x = 24 + c.offset_x * t
            c.y = 60
        return cnt > 32

    def anim_drop(self, chars, cnt):
        """Phase 3: 揃ったロゴがガシャンと下に沈み込む"""
        for c in chars:
            c.x = 24 + c.offset_x
            c.y = 60 + cnt
        return (60 + cnt) == 104

    def anim_stay(self, chars, cnt):
        """Phase 4: 定位置で静止して見せる"""
        for c in chars:
            c.x = 24 + c.offset_x
            c.y = 104
        return cnt > 60

    def draw(self, screen):
        # 全文字を描画
        for c in self.chars:
            c.draw(screen)

def main():
    clock = pygame.time.Clock()
    animator = LogoAnimator()
    running = True
    while running:
        for event in pygame.event.get():
            if event.type == pygame.QUIT:
                running = False
        animator.update()
        screen.fill(BLACK)
        animator.draw(screen)
        pygame.display.flip()
        clock.tick(60)  # 高速になりすぎないようウェイトを追加

    pygame.quit()
    sys.exit()

if __name__ == "__main__":
    main()
