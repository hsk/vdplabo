logo_data = [FONT_R, FONT_DOT, FONT_T, FONT_Y, FONT_P, FONT_E]
x_pos = [0, 15, 30, 50, 70, 90]

# 32x32サイズのスプライト（Surface）生成関数
def create_sprite_32(matrix):
    # 32x32の板を作成
    surf = pygame.Surface((32, 32))
    surf.fill((0,0,0))
    surf.set_colorkey((0, 0, 0))
    for y in range(16):
        for x in range(16):
            if matrix[y][x] == 1:
                # 1ドットを縦横2倍（2x2ピクセル）の矩形として描画し、32x32に拡大
                pygame.draw.rect(surf, WHITE, (x * 2, y * 2, 2, 2))
    return surf

# 6つの文字スプライト（32x32）をリスト化
sprites = [create_sprite_32(matrix) for matrix in logo_data]
def main():
    # メインループ
    running = True
    phase = 1
    cnt = 0
    clock = pygame.time.Clock()
    while running:
        screen.fill(BLACK)
        for event in pygame.event.get():
            if event.type == pygame.QUIT:
                running = False
        if phase == 1: next = anim1(cnt)
        elif phase == 2: next = anim2(cnt)
        elif phase == 3: next = anim3(cnt)
        elif phase == 4: next = anim4(cnt)
        cnt += 1
        if next:
            cnt = 0
            phase += 1
            if phase > 4: phase = 1
        clock.tick(60)  # 高速になりすぎないようウェイトを追加
        pygame.display.flip()
    pygame.quit()
    sys.exit()

def anim1(cnt):
    # 6つの拡大文字を並べて表示
    start_x = 256  # 画面中央付近にくるよう開始位置を調整
    start_y = 60  # 上下の中央付近に調整
    for i, sprite in enumerate(sprites):
        # x_pos の値も2倍にして描画位置を計算
        screen.blit(sprite, (start_x-cnt*4, start_y))
    return start_x-cnt*4 <= 24
def anim2(cnt):
    # 6つの拡大文字を並べて表示
    t = 1-(32-cnt)/32
    start_x = 24  # 画面中央付近にくるよう開始位置を調整
    start_y = 60  # 上下の中央付近に調整
    for i, sprite in enumerate(sprites):
        # x_pos の値も2倍にして描画位置を計算
        screen.blit(sprite, (start_x + x_pos[i]*2*t, start_y))
    return cnt > 32

def anim3(cnt):
    # 6つの拡大文字を並べて表示
    start_x = 24  # 画面中央付近にくるよう開始位置を調整
    start_y = 60  # 上下の中央付近に調整
    for i, sprite in enumerate(sprites):
        # x_pos の値も2倍にして描画位置を計算
        screen.blit(sprite, (start_x + x_pos[i] * 2, start_y+cnt))
    return (start_y + cnt) == 104
def anim4(cnt):
    # 6つの拡大文字を並べて表示
    start_x = 24  # 画面中央付近にくるよう開始位置を調整
    start_y = 104  # 上下の中央付近に調整
    for i, sprite in enumerate(sprites):
        # x_pos の値も2倍にして描画位置を計算
        screen.blit(sprite, (start_x + x_pos[i] * 2, start_y))
    return cnt > 60

main()