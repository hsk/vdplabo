class LogoChar:
    def __init__(self, matrix, index):
        X_OFFSETS = [0, 30, 60, 100, 140, 180]
        self.offset_x = X_OFFSETS[index]
        self.x, self.y = 256, 60
        self.image = self._create_image(matrix)

    def _create_image(self, matrix):
        surf = pygame.Surface((32, 32))
        surf.fill(BLACK)
        surf.set_colorkey(BLACK)
        for y in range(16):
            for x in range(16):
                if matrix[y][x] == 1:
                    pygame.draw.rect(surf, WHITE, (x * 2, y * 2, 2, 2))
        return surf

    def draw(self, surface):
        surface.blit(self.image, (int(self.x), int(self.y)))  # 座標を整数にして描画


class LogoAnimator:
    def __init__(self):
        self.chars = [LogoChar(matrix, i) for i, matrix in enumerate(LOGO_DATA)]
        self.phase = 0
        self.cnt = 0

        # ★ 演出の全スケジュールを「データ」として美しく定義
        # [演出時間(F), 横の広がり倍率(0=重なる, 1=定位置), 基準のX座標, 基準のY座標]
        self.SEQUENCE = [
            {"duration": 60, "expand": 0.0, "base_x": 257, "base_y": 60},  # P1: 重なって右から左へ
            {"duration": 60, "expand": 0.0, "base_x": 24, "base_y": 60},  # P1: 重なって右から左へ
            {"duration": 32, "expand": 1.0, "base_x": 24,  "base_y": 60},  # P2: 左端でアコーディオン展開
            {"duration": 44, "expand": 1.0, "base_x": 24,  "base_y": 104}, # P3: ガシャンと下に沈む
            {"duration": 60, "expand": 1.0, "base_x": 24,  "base_y": 104}, # P4: 定位置で静止
        ]

    def update(self):
        current_seq = self.SEQUENCE[self.phase]
        
        # 次の目標状態（データから取得）
        target_expand = current_seq["expand"]
        target_base_x = current_seq["base_x"]
        target_base_y = current_seq["base_y"]

        # ★ 【イージング（Lerp）】目標値に向かって滑らかに追従させる（割る値が大きいほど滑らか）
        # 前のフェーズの最後の状態から、次の目標へ自動で綺麗に繋がります
        for c in self.chars:
            # 各文字の理想の目的地を計算
            dest_x = target_base_x + (c.offset_x * target_expand)
            dest_y = target_base_y
            
            # 現在地を目的地にじわっと近づける（これだけで超滑らかな動きに！）
            c.x += (dest_x - c.x) * 0.2
            c.y += (dest_y - c.y) * 0.2

        # 時間経過で次のフェーズへ
        self.cnt += 1
        if self.cnt >= current_seq["duration"]:
            self.cnt = 0
            self.phase = (self.phase + 1) % len(self.SEQUENCE)

    def draw(self, screen):
        for c in self.chars:
            c.draw(screen)


def main():
    clock = pygame.time.Clock()
    animator = LogoAnimator()
    
    while True:
        for event in pygame.event.get():
            if event.type == pygame.QUIT:
                pygame.quit()
                sys.exit()

        animator.update()
        
        screen.fill(BLACK)
        animator.draw(screen)
        pygame.display.flip()
        clock.tick(60)

if __name__ == "__main__":
    main()
