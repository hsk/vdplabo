; MSX カセットROM SCREEN 2 スプライト1つ
; --- MSX BIOSのアドレス定義 ---
WRTVDP equ 00047h       ; VDPレジスタ書き込み (B=レジスタ, C=値)
CHGMOD equ 0005Fh       ; 画面モード変更 (Aレジスタでモード指定)
FILVRM equ 00056h       ; VRAM を一定値で埋める (A=値, BC=サイズ, HL=VRAM宛先)
LDIRVM equ 0005Ch       ; メモリからVRAMへ一括転送 (BC=サイズ, DE=VRAM宛先, HL=メモリ元)
WRTVRM equ 0004Dh       ; VRAMへ1バイト書き込み (A=値, HL=VRAMアドレス)
GTSTCK equ 000D5h
SNSMAT equ 00141h
KILBUF equ 00156h
SPRATR equ 01B00h       ; VRAMのスプライト属性テーブル起点アドレス
SPRPAT equ 03800h       ; VRAMのパターンジェネレータ起点アドレス
RG1SAV equ 0F3E0h       ; VDPレジスタ退避アドレス
JIFFY  equ 0FC9Eh
player_z equ 0C000h
player_y equ 0C001h
; --- ROMヘッダ ---
    org 04000h          ; カセットROMはページ2(04000h)に配置
rom_header:
    db "AB"             ; ROMの識別ID (04000h)
    dw init             ; 電源ON時に実行するアドレス (04002h)
    dw 0, 0, 0, 0, 0    ; 残りのヘッダ領域を0で埋める
; --- メインプログラム ---
init:
    ; SCREEN 2 の設定
    ld a, 2
    call CHGMOD
    ld hl,player_y
    ld (hl),0
    ; SCREEN2 のパターンテーブル先頭へ文字列を配置
    ld hl, 00000h
    ld b, 3
    send_pattern_table_loop:
        push bc
        ld b, 192/2
        send_pattern_table:
            ;      12345678
            ld a, 010101010b
            call WRTVRM
            inc hl
            ;      12345678
            ld a, 001010101b
            call WRTVRM
            inc hl
            djnz send_pattern_table
        ; ３つに分かれてる次のパターンテーブルの先頭に移動
        ld bc, 256*8 - 192
        add hl, bc
        pop bc
        djnz send_pattern_table_loop
    ; スプライトパターンネームテーブルを１ライン目が１、２ライン目が２として全画面を埋める。

    ; SCREEN2 パターンネームテーブル($1800-$1AFF)
    ; 1ライン目=パターン1、2ライン目=パターン2 を交互に配置
    ld hl, 1800h
    ld b, 24              ; 24行
    ld d, 0
    fill_name_table_y:
        push bc

        ld a, d
        fill_name_table_pattern_selected:

        ld c, 32              ; 1行32文字
        fill_name_table_x:
            call WRTVRM
            inc hl
            dec c
            jr nz, fill_name_table_x
        inc d
        pop bc
        djnz fill_name_table_y

    ; カラーテーブルをstripe_table_1の値をもとにstripe_color_tableを引いた値を設定する192ライン分設定する

main:
    ; VSYNC
    ld b, 4
    vsync_loop:
        ld hl, JIFFY
        ld a, (hl)
        vsync:
            cp (hl)
            jr z, vsync
        djnz vsync_loop

    ; キー入力
    call KILBUF
    xor a
    call GTSTCK
    ; 上チェック
    ld hl, player_y
    cp 0
    jr z, end_up        ; 0なら飛ぶ
    cp 3
    jr c, up            ; 1か2なら飛ぶ
    cp 8
    jr nz, end_up       ; 8でないなら飛ぶ
    up:
        ld c, a
        ld a, (hl)
        cp 0
        ld a, c
        jr z, end_up
        dec (hl)        ; 8,1,2 でdec
    end_up:
    ; 下チェック
    cp 4
    jr c, end_down      ; 4未満なら飛ぶ
    cp 7
    jr nc, end_down     ; 7以上なら飛ぶ
        ld a, (hl)
        cp 19
        jr nc, end_down
        inc (hl)        ; 4,5,6 でinc
    end_down:

    ; SCREEN2 カラーテーブル ($2000-$37FF)
    ; stripe_table_1 の値(0-4)を stripe_color_table で色コードへ変換
    ; 各ラインの色を8バイト分書き込む
    ld a,(hl)
    add a,a
    ld de, stripe_tables
    ld h,0
    ld l,a
    add hl, de
    ld e,(hl)
    inc hl
    ld d,(hl)
    ex de, hl
    ld de, 02000h
    ld b, 3
    color_table_loop:
        push bc
        ld b, 192/3
        color_table_y:
            push bc
            push hl

            ld a, (hl)
            cp 4
            jr z, color_table_skip
                ld c, a
                ld a, (player_z)
                add a, c
                and 3
            color_table_skip:

            ld hl, stripe_color_table
            ld c, a
            ld b, 0
            add hl, bc
            ld a, (hl)
            pop hl
            ex de, hl
            call WRTVRM
            inc hl
            ex de, hl
            inc hl
            pop bc
            djnz color_table_y
        ex de, hl
        ld bc, 256*8
        add hl, bc
        ex de, hl
        pop bc
        djnz color_table_loop
    ld hl, player_z
    inc (hl)

    jr main             ; 画面を維持するため無限ループ

